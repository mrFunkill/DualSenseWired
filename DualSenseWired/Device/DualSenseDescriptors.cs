    public static byte[] StringDescriptor(string s)
    {
        var b = new byte[2 + 2 * s.Length];
        b[0] = (byte)b.Length;
        b[1] = 0x03;
        for (int i = 0; i < s.Length; i++)
        {
            b[2 + 2 * i] = (byte)s[i];
            b[3 + 2 * i] = (byte)(s[i] >> 8);
        }
        return b;
    }
